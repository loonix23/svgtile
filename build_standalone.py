#!/usr/bin/env python3
"""Regenerate svgtile-standalone.py from svgpath.py + svgdoc.py + svgtile.py.

The standalone file is a build artifact: never edit it by hand.
Run: python3 build_standalone.py          (writes the file)
     python3 build_standalone.py --check  (exit 1 if it is out of date)
"""
import ast, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, 'svgtile-standalone.py')
# (module, section heading) in dependency order
MODULES = [
    ('svgpath.py', 'SVG path parsing'),
    ('svgdoc.py', 'SVG document -> polylines in cm'),
    ('svgtile.py', 'tiling + PDF output'),
]
LOCAL = {os.path.splitext(m)[0] for m, _ in MODULES}
HEADER = '''#!/usr/bin/env python3
"""
svgtile - split an SVG into glue-together A4 PDF sheets at true 1:1 scale.
Single-file build. Requires: reportlab, lxml.
Copyright (c) 2026 loonix23. MIT License - see LICENSE in the source distribution.
Docs + tests: see README.md in the source distribution.
GENERATED by build_standalone.py - edit svgpath.py / svgdoc.py / svgtile.py instead.
"""
'''


def split_module(src):
    """Return (import_lines, body) with shebang, module docstring and
    top-level imports removed. Imports of sibling modules are dropped."""
    tree = ast.parse(src)
    lines = src.splitlines()
    drop = set()
    imports = []
    for i, node in enumerate(tree.body):
        span = range(node.lineno - 1, node.end_lineno)
        if i == 0 and isinstance(node, ast.Expr) and isinstance(node.value, ast.Constant) \
                and isinstance(node.value.value, str):
            drop.update(span)
        elif isinstance(node, (ast.Import, ast.ImportFrom)):
            drop.update(span)
            mod = node.module if isinstance(node, ast.ImportFrom) else node.names[0].name
            if mod.split('.')[0] not in LOCAL:
                imports.append(ast.get_source_segment(src, node))
    body = [l for n, l in enumerate(lines) if n not in drop and not (n == 0 and l.startswith('#!'))]
    return imports, '\n'.join(body).strip('\n')


def build():
    plain, froms, bodies = set(), [], []
    for fname, title in MODULES:
        with open(os.path.join(HERE, fname)) as f:
            imports, body = split_module(f.read())
        for imp in imports:
            if imp.startswith('import '):
                plain.update(n.strip() for n in imp[len('import '):].split(','))
            elif imp not in froms:
                froms.append(imp)
        bodies.append(f"# {'=' * 68}\n# {title}\n# {'=' * 68}\n\n{body}\n")
    head = HEADER + '\n'.join(sorted(froms)) + '\n' + f"import {', '.join(sorted(plain))}\n"
    return head + '\n' + '\n'.join(bodies)


def main():
    text = build()
    if '--check' in sys.argv:
        with open(OUT) as f:
            if f.read() != text:
                sys.exit('svgtile-standalone.py is out of date: run python3 build_standalone.py')
        print('svgtile-standalone.py is up to date')
        return
    with open(OUT, 'w') as f:
        f.write(text)
    os.chmod(OUT, 0o755)
    print(f'wrote {OUT}')


if __name__ == '__main__':
    main()
